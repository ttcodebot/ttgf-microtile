"""
Capacity sweep: turns this repository (in place) into another micro tile project.

  gen.py synthetic --flops N --logic K [--density D]
      A parametric design: an N bit state register, where the next value of each
      bit is the previous bit mixed with K (AND/OR, XOR) gate pairs fed by other
      bits. ui_in is mixed into the first 8 bits, uo_out is an XOR fold of all
      the bits, so all the inputs and outputs are used.

  gen.py wokwi --wokwi-id ID [--density D]
      A Wokwi project. The tools fetch its Verilog with the micro tile port list.

The changes are not meant to be committed: the sweep workflow applies them on a
fresh checkout before hardening.
"""

import argparse
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.realpath(__file__)))
TAPS = [(3, 7), (11, 5), (13, 17), (19, 2), (23, 29), (31, 37)]


def synthetic_verilog(flops: int, logic: int) -> str:
    n = flops
    lines = [
        "`default_nettype none",
        "",
        f"// Generated by sweep/gen.py: {n} flops, {logic} gate pairs per flop",
        "module tt_um_micro_sweep (",
        "    input  wire [7:0] ui_in,",
        "    output wire [7:0] uo_out,",
        "    input  wire       clk,",
        "    input  wire       rst_n",
        ");",
        "",
        f"  reg  [{n - 1}:0] s;",
        f"  wire [{n - 1}:0] nxt;",
        "",
    ]
    for i in range(n):
        expr = f"s[{(i + n - 1) % n}]"
        if i < 8:
            expr = f"({expr} ^ ui_in[{i}])"
        for k in range(logic):
            a, b = TAPS[k % len(TAPS)]
            sa, sb = f"s[{(i + a) % n}]", f"s[{(i + b) % n}]"
            op = "&" if k % 2 == 0 else "|"
            expr = f"({expr} ^ ({sa} {op} {sb}))"
        lines.append(f"  assign nxt[{i}] = {expr};")
    lines += [
        "",
        "  always @(posedge clk or negedge rst_n)",
        f"    if (~rst_n) s <= {n}'d0;",
        "    else s <= nxt;",
        "",
    ]
    for j in range(8):
        bits = [f"s[{i}]" for i in range(n) if i % 8 == j] or ["1'b0"]
        lines.append(f"  assign uo_out[{j}] = {' ^ '.join(bits)};")
    lines += ["", "endmodule", ""]
    return "\n".join(lines)


def update_info(replacements):
    path = os.path.join(ROOT, "info.yaml")
    with open(path) as f:
        text = f.read()
    for pattern, replacement in replacements:
        text, count = re.subn(pattern, replacement, text, flags=re.M)
        assert count == 1, pattern
    with open(path, "w") as f:
        f.write(text)


def set_density(density: int):
    path = os.path.join(ROOT, "src", "config.json")
    with open(path) as f:
        text = f.read()
    text, count = re.subn(
        r'"PL_TARGET_DENSITY_PCT": \d+', f'"PL_TARGET_DENSITY_PCT": {density}', text
    )
    assert count == 1
    with open(path, "w") as f:
        f.write(text)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("kind", choices=["synthetic", "wokwi"])
    parser.add_argument("--flops", type=int, default=32)
    parser.add_argument("--logic", type=int, default=1)
    parser.add_argument("--wokwi-id", default="")
    parser.add_argument("--density", type=int, default=60)
    args = parser.parse_args()

    set_density(args.density)
    point = {"kind": args.kind, "density": args.density}
    if args.kind == "synthetic":
        with open(os.path.join(ROOT, "src", "tt_um_micro_sweep.v"), "w") as f:
            f.write(synthetic_verilog(args.flops, args.logic))
        update_info(
            [
                (
                    r'top_module:\s+"tt_um_micro_test"',
                    'top_module:  "tt_um_micro_sweep"',
                ),
                (r'- "tt_um_micro_test.v"', '- "tt_um_micro_sweep.v"'),
            ]
        )
        point.update(param_flops=args.flops, param_logic=args.logic)
    else:
        # Wokwi projects: top_module and source_files are derived from the id
        update_info(
            [
                (r"^project:$", f"project:\n  wokwi_id:     {args.wokwi_id}"),
                (r'language:\s+"Verilog"', 'language:     "Wokwi"'),
                (r'^\s*top_module:\s+"tt_um_micro_test"\n', ""),
                (r'^\s*source_files:\s*\n\s*- "tt_um_micro_test.v"\n', ""),
            ]
        )
        with open(os.path.join(ROOT, "sweep", "cells.v")) as f:
            cells = f.read()
        with open(os.path.join(ROOT, "src", "cells.v"), "w") as f:
            f.write(cells)
        point.update(wokwi_id=args.wokwi_id)
    with open(os.path.join(ROOT, "sweep", "point.json"), "w") as f:
        json.dump(point, f)


if __name__ == "__main__":
    main()
